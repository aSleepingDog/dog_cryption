	for (uint64_t i = 0; i < S.size() / 2; i++)
	{
		std::swap(S[i], S[S.size() - i - 1]);
	}
	uint32_t P[4] = { 0 };
	P[0] = (uint32_t)crypt[0] | crypt[1] << 8 | crypt[2] << 16 | crypt[3] << 24;
