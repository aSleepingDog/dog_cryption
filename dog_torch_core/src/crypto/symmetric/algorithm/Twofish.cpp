		P[3] = dog_torch::math::integer::CRMB(P[3], 1);
		std::swap(P[0], P[2]);
		std::swap(P[1], P[3]);
		//printf("%08X %08X %08X %08X T0=%08X T1=%08X\n", P[0], P[1], P[2], P[3], T0, T1);
