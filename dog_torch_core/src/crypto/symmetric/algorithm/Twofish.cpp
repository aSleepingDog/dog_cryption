	w[3] = (uint32_t)key[key_size / 2 + 12] << 24 | (uint32_t)key[key_size / 2 + 13] << 16 | (uint32_t)key[key_size / 2 + 14] << 8 | (uint32_t)key[key_size / 2 + 15];
	std::swap(P[0], P[2]);
	std::swap(P[1], P[3]);
	P[0] ^= w[0];
	P[1] ^= w[1];
	P[2] ^= w[2];
	P[3] ^= w[3];
	//for (int i = 0; i < 4; i++)
